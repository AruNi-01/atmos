function SelectLoadMoreFooter({
  hasMore,
  loading,
  onLoadMore,
  label,
  loadingLabel,
}: {
  hasMore: boolean;
  loading: boolean;
  onLoadMore: () => void;
  label: string;
  loadingLabel: string;
}) {
  if (!hasMore) return null;
  return (
    <div
      className="sticky bottom-0 z-10 border-t border-border/60 bg-popover px-2 py-1.5"
      onPointerDown={(event) => event.preventDefault()}
    >
      <button
        type="button"
        className="flex w-full items-center justify-center gap-1.5 rounded-md px-2 py-1.5 text-xs font-medium text-muted-foreground hover:bg-muted hover:text-foreground disabled:opacity-60"
        disabled={loading}
        onClick={(event) => {
          event.preventDefault();
          event.stopPropagation();
          onLoadMore();
        }}
      >
        {loading ? <Loader2 className="size-3.5 animate-spin" /> : null}
        {loading ? loadingLabel : label}
      </button>
    </div>
  );
}

function IssueLinkPanel({
  autoExtractDescription,
  autoExtractTodos,
  canAutoExtractTodos,
  handleLoadIssueFromUrl,
  handleLoadMoreIssues,
  handleSelectIssue,
  isIssuePreviewLoading,
  isIssuesLoading,
  isIssuesLoadingMore,
  issueError,
  issuePreview,
  issues,
  issuesHasMore,
  issueUrl,
  onIssueUrlChange,
  repoContext,
  selectedIssueNumber,
  selectedProjectId,
  setAutoExtractTodos,
}: {
  autoExtractDescription: string;
  autoExtractTodos: boolean;
  canAutoExtractTodos: boolean;
  handleLoadIssueFromUrl: () => void | Promise<void>;
  handleLoadMoreIssues: () => void | Promise<void>;
  handleSelectIssue: (value: string) => void;
  isIssuePreviewLoading: boolean;
  isIssuesLoading: boolean;
  isIssuesLoadingMore: boolean;
  issueError: string | null;
  issuePreview: GithubIssuePayload | null;
  issues: GithubIssuePayload[];
  issuesHasMore: boolean;
  issueUrl: string;
  onIssueUrlChange: (value: string) => void;
  repoContext: RepoContext | null;
  selectedIssueNumber: string;
  selectedProjectId: string | null;
  setAutoExtractTodos: (value: boolean) => void;
}) {
  const t = useTranslations("Welcome.components");
  return (
    <div className="border-t border-border/60 p-4">
      <div className="space-y-4">
        {repoContext ? (
          <div className="grid min-w-0 gap-4 md:grid-cols-[minmax(0,1fr)_auto]">
            <div className="grid min-w-0 gap-2">
              <Label htmlFor="issue-select-inline">{t("advanced.issue.selectFromRepository")}</Label>
              <Select
                value={selectedIssueNumber}
                onValueChange={handleSelectIssue}
                disabled={!isIssuesLoading && issues.length === 0}
              >
                <SelectTrigger
                  id="issue-select-inline"
                  className="w-full min-w-0 [&>span]:flex [&>span]:min-w-0 [&>span]:flex-1 [&>span]:truncate"
                >
                  <SelectValue
                    placeholder={
                      isIssuesLoading
                        ? t("advanced.issue.loadingIssues")
                        : issues.length === 0
                          ? t("advanced.issue.noIssuesAvailable")
                          : t("advanced.issue.selectIssue")
                    }
                  />
                </SelectTrigger>
                <SelectContent className="max-h-80">
                  {issues.length === 0 ? (
                    <div className="px-2 py-1.5 text-xs text-muted-foreground">
                      {t("advanced.issue.noGithubIssuesFound")}
                    </div>
                  ) : (
                    issues.map((issue) => (
                      <SelectItem key={issue.number} value={String(issue.number)}>
                        <div className="flex min-w-0 items-center gap-2">
                          <span className="font-mono text-xs text-muted-foreground">
                            #{issue.number}
                          </span>
                          <span className="truncate">{issue.title}</span>
                        </div>
                      </SelectItem>
                    ))
                  )}
                  <SelectLoadMoreFooter
                    hasMore={issuesHasMore}
                    loading={isIssuesLoadingMore}
                    onLoadMore={() => void handleLoadMoreIssues()}
                    label={t("advanced.loadMore")}
                    loadingLabel={t("advanced.loadingMore")}
                  />
                </SelectContent>
              </Select>
            </div>

            <div className="grid gap-2">
              <Label htmlFor="issue-url-inline">{t("advanced.issue.pasteIssueUrl")}</Label>
              <div className="flex gap-2">
                <Input
                  id="issue-url-inline"
                  value={issueUrl}
                  onChange={(event) => onIssueUrlChange(event.target.value)}
                  placeholder={t("advanced.issue.issueUrlPlaceholder", { owner: repoContext.owner, repo: repoContext.repo })}
                />
                <Button
                  type="button"
                  variant="outline"
                  size="icon"
                  onClick={() => void handleLoadIssueFromUrl()}
                  disabled={isIssuePreviewLoading || !issueUrl.trim()}
                  title={t("advanced.issue.loadIssue")}
                >
                  {isIssuePreviewLoading ? (
                    <Loader2 className="size-4 animate-spin" />
                  ) : (
                    <CloudDownload className="size-4" />
                  )}
                </Button>
              </div>
            </div>
          </div>
        ) : selectedProjectId ? (
          <div className="rounded-xl border border-dashed border-border/70 px-3 py-4 text-sm text-muted-foreground">
            {t("advanced.issue.projectNoGithubRemote")}
          </div>
        ) : (
          <div className="rounded-xl border border-dashed border-border/70 px-3 py-4 text-sm text-muted-foreground">
            {t("advanced.issue.selectProjectFirst")}
          </div>
        )}

        {issueError ? (
          <div className="rounded-xl border border-destructive/30 bg-destructive/8 px-3 py-2 text-xs text-destructive">
            {issueError}
          </div>
        ) : null}

        {isIssuePreviewLoading ? (
          <div className="flex items-center gap-2 rounded-xl border border-border/70 px-3 py-4 text-sm text-muted-foreground">
            <Loader2 className="size-4 animate-spin" />
            {t("advanced.issue.loadingIssuePreview")}
          </div>
        ) : issuePreview ? (
          <GithubPreviewCard
            bodyFallback={t("advanced.issue.noIssueDescription")}
            labels={issuePreview.labels}
            owner={issuePreview.owner}
            repo={issuePreview.repo}
            number={issuePreview.number}
            state={issuePreview.state}
            title={issuePreview.title}
            url={issuePreview.url}
            body={issuePreview.body}
          />
        ) : null}

        <AutoExtractTodosCheckbox
          checked={autoExtractTodos}
          description={autoExtractDescription}
          disabled={!canAutoExtractTodos}
          onChange={setAutoExtractTodos}
        />
      </div>
    </div>
  );
}


  baseBranchFilter: string;
  branch: string;
  branchError: string | null;
  branchInputRef: React.RefObject<HTMLInputElement | null>;
  canAutoExtractTodosIssue: boolean;
  canAutoExtractTodosPr: boolean;
  displayedLinkType: "issue" | "pr" | "linear";
  filteredRemoteBranches: string[];
  handleLoadIssueFromUrl: () => void | Promise<void>;
  handleLoadMoreIssues: () => void | Promise<void>;
  handleLoadMoreLinear: () => void | Promise<void>;
  handleLoadMorePrs: () => void;
  handleLoadPrFromUrl: () => void | Promise<void>;
  handleRefreshIssues: () => void | Promise<void>;
  handleRefreshLinear: () => void | Promise<void>;
  handleRefreshPrs: () => void | Promise<void>;
  handleRegenerateBranch: () => void;
  handleSelectIssue: (value: string) => void;
  handleSelectLinear: (value: string) => void;
  handleSelectLinkType: (next: "issue" | "pr" | "linear") => void;
  handleSelectPr: (value: string) => void;
  isAdvancedOpen: boolean;
  isBaseBranchesLoading: boolean;
  isBaseBranchOpen: boolean;
  isIssuePreviewLoading: boolean;
  isIssuesLoading: boolean;
  isIssuesLoadingMore: boolean;
  isLinearLoading: boolean;
  isLinearLoadingMore: boolean;
  isPrPreviewLoading: boolean;
  isPrsLoading: boolean;
  isPrsLoadingMore: boolean;
  issueError: string | null;
  issuePreview: GithubIssuePayload | null;
  issues: GithubIssuePayload[];
  issuesHasMore: boolean;
  issueUrl: string;
  linearConnected: boolean;
  linearError: string | null;

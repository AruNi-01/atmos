const { readFileSync } = require("node:fs");
const path = require("node:path");
const { describe, expect, test } = require("bun:test");

const app = JSON.parse(readFileSync(path.join(__dirname, "app.json"), "utf8"));

function pluginName(plugin) {
  return Array.isArray(plugin) ? plugin[0] : plugin;
}

describe("iOS launch scene", () => {
  test("installs the scene lifecycle plugin instead of a bare manifest", () => {
    const plugins = (app.expo.plugins ?? []).map(pluginName);
    expect(plugins).toContain("./plugins/with-ios-scene-lifecycle.js");
    expect(plugins).not.toContain("./plugins/with-ios-clear-tab-bar.js");
    expect(JSON.stringify(app.expo.plugins)).not.toContain("clear-tab-bar");
    // The class is generated by the plugin during prebuild. A manifest in
    // app.json without that class is the old black-window failure.
    expect(app.expo.ios.infoPlist.UIApplicationSceneManifest).toBeUndefined();
    expect(JSON.stringify(app.expo.ios.infoPlist)).not.toContain("SceneDelegate");
    expect(app.expo.ios.infoPlist.NSPhotoLibraryUsageDescription).toContain("photos");
    expect(app.expo.ios.infoPlist.NSPhotoLibraryAddUsageDescription).toContain("photos");
    expect(app.expo.ios.infoPlist.NSCameraUsageDescription).toContain("camera");
  });
});
